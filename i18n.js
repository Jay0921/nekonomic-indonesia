/* ---------- engine ---------- */

function t(key) {
  const path = key.split(".");
  let node = I18N[CURRENT_LOCALE];
  for (const p of path) {
    node = node && node[p];
  }
  if (node === undefined) {
    // fall back to English so a missing id translation never breaks the page
    node = I18N.en;
    for (const p of path) node = node && node[p];
  }
  return node === undefined ? key : node;
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.innerHTML = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.title = t("meta.title");
  document.querySelectorAll("[data-locale-btn]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.getAttribute("data-locale-btn") === CURRENT_LOCALE);
  });
}

function setLocale(locale) {
  if (locale !== "en" && locale !== "id") return;
  CURRENT_LOCALE = locale;
  document.documentElement.lang = locale;
  try {
    localStorage.setItem("nekonomic_locale", locale);
  } catch (e) {
    /* localStorage unavailable — locale just won't persist */
  }
  applyI18n();
  document.dispatchEvent(new CustomEvent("locale-changed", { detail: { locale } }));
}

document.addEventListener("DOMContentLoaded", () => {
  let stored = null;
  try {
    stored = localStorage.getItem("nekonomic_locale");
  } catch (e) {
    /* ignore */
  }
  CURRENT_LOCALE = stored === "id" ? "id" : "en";
  document.documentElement.lang = CURRENT_LOCALE;
  applyI18n();

  document.querySelectorAll("[data-locale-btn]").forEach((btn) => {
    btn.addEventListener("click", () => setLocale(btn.getAttribute("data-locale-btn")));
  });
});
